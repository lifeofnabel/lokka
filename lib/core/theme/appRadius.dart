class AppRadius {
  const AppRadius._();

  /// Modern, tighter corner scale — one source of truth for the whole app.
  /// small = chips/badges/inner elements, medium = inputs/small cards,
  /// large = cards/tiles, xl = sheets/dialogs, xxl = hero surfaces,
  /// full = pills/round buttons.
  static const small = 8.0;
  static const medium = 12.0;
  static const large = 16.0;
  static const xl = 24.0;
  static const xxl = 28.0;
  static const full = 999.0;
}
